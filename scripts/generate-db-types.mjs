import { readFile, writeFile } from "node:fs/promises";
import { replay } from "../tests/database/harness.mjs";

const db = await replay();
try {
  const tables = (await db.query(`select table_name, table_type from information_schema.tables
    where table_schema='public' order by table_name`)).rows;
  let output = "// Generated by npm run db:types from clean migrations. Do not edit.\n";
  output += "export type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];\n\n";
  output += "export type Database = { public: {\n  Tables: {\n";
  const render = async(table, view) => {
    const columns=(await db.query(`select column_name,data_type,udt_name,is_nullable,column_default,is_generated
      from information_schema.columns where table_schema='public' and table_name=$1 order by ordinal_position`,[table])).rows;
    const type = c => {
      let t = c.data_type === "jsonb" ? "Json" :
        c.data_type === "boolean" ? "boolean" :
        ["integer","bigint","numeric","smallint","real","double precision"].includes(c.data_type) ? "number" :
        c.data_type === "ARRAY" ? (c.udt_name === "_int4" ? "number[]" : "string[]") : "string";
      if(c.is_nullable==="YES") t += " | null";
      return t;
    };
    const fields = mode => columns.map(c=>{
      if(mode!=="Row" && c.is_generated==="ALWAYS") return "        "+c.column_name+"?: never;";
      const optional = mode==="Update" || (mode==="Insert" && (c.is_nullable==="YES" || c.column_default));
      return "        "+c.column_name+(optional?"?":"")+": "+type(c)+";";
    }).join("\n");
    let out="    "+table+": {\n      Row: {\n"+fields("Row")+"\n      };\n";
    if(!view) out+="      Insert: {\n"+fields("Insert")+"\n      };\n      Update: {\n"+fields("Update")+"\n      };\n";
    const fks=(await db.query(`select c.conname,
      array(select a.attname from unnest(c.conkey) with ordinality k(n,o) join pg_attribute a on a.attrelid=c.conrelid and a.attnum=k.n order by k.o) cols,
      target.relname target,
      array(select a.attname from unnest(c.confkey) with ordinality k(n,o) join pg_attribute a on a.attrelid=c.confrelid and a.attnum=k.n order by k.o) target_cols
      from pg_constraint c join pg_class owner on owner.oid=c.conrelid
      join pg_class target on target.oid=c.confrelid join pg_namespace n on n.oid=target.relnamespace
      where c.contype='f' and c.conrelid=('public.' || $1)::regclass and n.nspname='public' order by c.conname`,[table])).rows;
    out+="      Relationships: [\n"+fks.map(f=>"        { foreignKeyName: "+JSON.stringify(f.conname)+"; columns: "+JSON.stringify(f.cols)+"; isOneToOne: false; referencedRelation: "+JSON.stringify(f.target)+"; referencedColumns: "+JSON.stringify(f.target_cols)+" },").join("\n")+"\n      ];\n    };\n";
    return out;
  };
  for(const t of tables.filter(t=>t.table_type==="BASE TABLE")) output+=await render(t.table_name,false);
  output+="  };\n  Views: {\n";
  for(const t of tables.filter(t=>t.table_type==="VIEW")) output+=await render(t.table_name,true);
  const functions = (await db.query(`select p.proname, p.proargnames, array(select format_type(t,null) from unnest(p.proargtypes::oid[]) t) argtypes, format_type(p.prorettype,null) result from pg_proc p join pg_namespace n on n.oid=p.pronamespace where n.nspname='public' order by p.proname`)).rows;
  const scalar = t => t === "jsonb" ? "Json" : ["integer","bigint","numeric"].includes(t) ? "number" : t === "boolean" ? "boolean" : "string";
  output+="  };\n  Functions: {\n" + functions.map(f=>"    "+f.proname+": { Args: { "+f.proargnames.map((n,i)=>n+": "+scalar(f.argtypes[i])).join("; ")+" }; Returns: "+scalar(f.result)+" };").join("\n") + "\n  };\n  Enums: { [_ in never]: never };\n  CompositeTypes: { [_ in never]: never };\n} };\n";
  const file=new URL("../src/lib/supabase/database.types.ts",import.meta.url);
  if(process.argv.includes("--check")) {
    if(await readFile(file,"utf8")!==output) throw new Error("Database types are stale; run npm run db:types");
    console.log("Database types match clean migrations.");
  } else { await writeFile(file,output); console.log("Generated database types."); }
} finally { await db.close(); }

